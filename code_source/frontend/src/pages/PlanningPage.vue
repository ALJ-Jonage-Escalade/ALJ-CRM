<script setup lang="ts">
/* Planning (coaches and admins): the week's slots on a grid or in a table, create / edit / delete, print, Excel
   exports. Online only: nothing is kept on the device. */
import { DropdownMenuContent, DropdownMenuItem, DropdownMenuPortal, DropdownMenuRoot, DropdownMenuTrigger } from "reka-ui";
import { computed, inject, nextTick, onMounted, ref } from "vue";
import AppShell from "../components/AppShell.vue";
import UiButton from "../components/ui/UiButton.vue";
import UiCard from "../components/ui/UiCard.vue";
import UiDialog from "../components/ui/UiDialog.vue";
import UiToast from "../components/ui/UiToast.vue";
import { useToast } from "../composables/toast";
import { CLIENT_KEY, errorText } from "../lib/client";
import { createActivitiesApi } from "../services/activities";
import { createMembersApi } from "../services/members";
import { saveExport } from "../lib/download";
import SlotForm from "./planning/SlotForm.vue";
import SlotList from "./planning/SlotList.vue";
import { countLabel, draftOf, filterSlots, KINDS, updateOf, type KindFilter, type Slot, type SlotDraft } from "./planning/slots";
import WeekGrid from "./planning/WeekGrid.vue";

const client = inject(CLIENT_KEY)!;
const activitiesApi = createActivitiesApi(client);
const membersApi = createMembersApi(client);
const toast = useToast();

const slots = ref<Slot[]>([]);
const status = ref("Chargement…");
const tarifs = ref<string[]>([]);

async function loadPlanning(): Promise<void> {
  status.value = "Chargement…";
  try {
    slots.value = await activitiesApi.planning();
    status.value = countLabel(slots.value.length);
  } catch (e) {
    status.value = "Erreur chargement";
    toast.show(`❌ Impossible de charger le planning : ${errorText(e)}`, 8000);
  }
}

async function loadTarifs(): Promise<void> {
  try {
    tarifs.value = (await membersApi.seasonTarifs()).tarifs;
  } catch (e) {
    console.warn("Tarifs de la saison :", e);
  }
}

async function refresh(): Promise<void> {
  await loadPlanning();
  toast.show("🔄 Planning réactualisé.");
}

// Views
const view = ref<"week" | "table">("week");
const search = ref("");
const kind = ref<KindFilter>("all");
const shown = computed(() => filterSlots(slots.value, search.value, kind.value));

async function print(): Promise<void> {
  view.value = "week";
  await nextTick();
  window.print();
}

// Create and edit
const editing = ref(false);
const draft = ref<SlotDraft>(draftOf());
const saving = ref(false);
const dialogTitle = computed(() => (draft.value.id ? `✏️ Modifier le créneau #${draft.value.id}` : "➕ Nouveau créneau"));

function open(slot?: Slot): void {
  draft.value = draftOf(slot);
  editing.value = true;
}

async function save(): Promise<void> {
  saving.value = true;
  try {
    const saved = await activitiesApi.saveSlot(updateOf(draft.value));
    editing.value = false;
    toast.show(`✅ Créneau « ${saved.item.groupe} » enregistré !`);
    await loadPlanning();
  } catch (e) {
    toast.show(`❌ Échec : ${errorText(e)}`, 8000);
  } finally {
    saving.value = false;
  }
}

async function remove(slot: Slot): Promise<void> {
  if (!confirm(`Voulez-vous vraiment supprimer le créneau « ${slot.groupe} » (${slot.jour} ${slot.horaires}) ?`)) {
    return;
  }
  try {
    await activitiesApi.removeSlot(slot.id);
    toast.show("🗑️ Créneau supprimé.");
    await loadPlanning();
  } catch (e) {
    toast.show(`❌ Impossible de supprimer ce créneau : ${errorText(e)}`, 8000);
  }
}

// Excel exports, generated by the server
async function download(mode: "grid" | "list"): Promise<void> {
  toast.show("⏳ Génération du fichier Excel en cours…", 60_000);
  try {
    const name = await saveExport(activitiesApi.planningFile(mode), mode === "list" ? "Planning_Liste.xlsx" : "Planning_Grille.xlsx");
    toast.show(`✅ Fichier « ${name} » téléchargé !`);
  } catch (e) {
    toast.show(`❌ Échec lors de la génération Excel : ${errorText(e)}`, 8000);
  }
}

onMounted(() => {
  void loadPlanning();
  void loadTarifs();
});

const chip = (active: boolean) => [
  "cursor-pointer rounded-full border px-3 py-1 text-xs font-semibold",
  active ? "border-accent bg-accent text-white" : "border-slate-300 bg-white text-slate-600 hover:bg-slate-50",
];
const menuItem = "block cursor-pointer px-3 py-2 text-[12.5px] outline-none data-highlighted:bg-slate-100";
</script>

<template>
  <AppShell page="planning" title="Planning & Créneaux">
    <UiCard class="mb-3 print:hidden">
      <div class="flex flex-wrap items-center justify-between gap-2.5">
        <div class="min-w-0">
          <h2 class="text-base font-bold">📅 Planning & gestion des créneaux</h2>
          <p class="text-xs text-slate-500">
            Création, modification des créneaux, animateurs, tarifs HelloAsso et impression de la grille.
          </p>
        </div>
        <div class="flex flex-wrap items-center gap-2">
          <UiButton data-testid="slot-new" @click="open()">➕ Nouveau créneau</UiButton>
          <UiButton variant="muted" data-testid="planning-print" @click="print">🖨️ Imprimer la grille</UiButton>
          <DropdownMenuRoot>
            <DropdownMenuTrigger as-child>
              <UiButton variant="muted" data-testid="export-menu">📥 Exporter Excel ▾</UiButton>
            </DropdownMenuTrigger>
            <DropdownMenuPortal>
              <DropdownMenuContent
                align="end"
                :side-offset="4"
                class="z-50 min-w-52 overflow-hidden rounded-lg border border-slate-200 bg-white shadow-lg"
              >
                <DropdownMenuItem data-testid="export-grid" :class="menuItem" @select="download('grid')"
                  >📊 Grille hebdomadaire (.xlsx)</DropdownMenuItem
                >
                <DropdownMenuItem data-testid="export-list" :class="menuItem" @select="download('list')"
                  >📋 Liste des créneaux (.xlsx)</DropdownMenuItem
                >
              </DropdownMenuContent>
            </DropdownMenuPortal>
          </DropdownMenuRoot>
          <UiButton
            variant="muted"
            small
            data-testid="planning-refresh"
            aria-label="Recharger le planning"
            title="Recharger le planning"
            @click="refresh"
            >🔄</UiButton
          >
        </div>
      </div>
      <div class="mt-2.5 flex flex-wrap items-center justify-between gap-2 border-t border-slate-100 pt-2">
        <div class="flex flex-wrap gap-1.5">
          <button
            type="button"
            data-testid="view-week"
            :aria-pressed="view === 'week'"
            :class="chip(view === 'week')"
            @click="view = 'week'"
          >
            🗓️ Vue semaine
          </button>
          <button
            type="button"
            data-testid="view-table"
            :aria-pressed="view === 'table'"
            :class="chip(view === 'table')"
            @click="view = 'table'"
          >
            📋 Tableau des créneaux
          </button>
        </div>
        <span data-testid="slot-count" class="rounded-full bg-slate-200 px-2.5 py-0.5 text-xs font-semibold text-slate-600">{{
          status
        }}</span>
      </div>
    </UiCard>

    <WeekGrid v-if="view === 'week'" :slots="slots" @open="open" />

    <div v-else class="flex flex-col gap-2.5">
      <UiCard class="flex flex-wrap items-center gap-2">
        <input
          v-model="search"
          type="search"
          data-testid="slot-search"
          aria-label="Filtrer les créneaux"
          placeholder="🔍 Filtrer les créneaux (nom, jour, encadrant, tarif)…"
          class="min-w-0 flex-1 basis-60 rounded-lg border border-slate-300 px-2.5 py-1.5 text-[12.5px]"
        />
        <div class="flex flex-wrap gap-1.5">
          <button
            v-for="[value, label] in KINDS"
            :key="value"
            type="button"
            :data-testid="`kind-${value}`"
            :aria-pressed="kind === value"
            :class="chip(kind === value)"
            @click="kind = value"
          >
            {{ label }}
          </button>
        </div>
      </UiCard>
      <SlotList :slots="shown" @edit="open" @remove="remove" />
    </div>

    <UiDialog v-model:open="editing" :title="dialogTitle" wide data-testid="slot-dialog">
      <SlotForm
        v-if="editing"
        v-model="draft"
        :tarifs="tarifs"
        :saving="saving"
        @save="save"
        @invalid="toast.show"
        @cancel="editing = false"
      />
    </UiDialog>
    <UiToast :message="toast.message.value" />
  </AppShell>
</template>

<style>
@media print {
  @page {
    size: landscape;
    margin: 8mm;
  }
}
</style>
