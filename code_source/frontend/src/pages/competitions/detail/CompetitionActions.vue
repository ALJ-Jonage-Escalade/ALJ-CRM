<script setup lang="ts">
/* The actions on one competition, for coaches and admins: edit, e-mail its competitors (in the « Plus » menu on a
   phone, where writing an e-mail is rare), the « Plus » menu (load the « Compétition » group, MyCompet results, exports, archive, remove the never invited, delete). What changes the list
   of competitors is the detail's (emitted); the competition itself, its results and exports are handled here. */
import { inject, ref } from "vue";
import { useRouter } from "vue-router";
import UiButton from "../../../components/ui/UiButton.vue";
import UiDialog from "../../../components/ui/UiDialog.vue";
import UiDialogActions from "../../../components/ui/UiDialogActions.vue";
import UiMenu from "../../../components/ui/UiMenu.vue";
import UiMenuItem from "../../../components/ui/UiMenuItem.vue";
import { dialogs } from "../../../composables/dialogs";
import { useWideLayout } from "../../../composables/media";
import { CLIENT_KEY, errorText, type Schemas } from "../../../lib/client";
import { csvBlob } from "../../../lib/csv";
import { saveExport, saveFile } from "../../../lib/download";
import { createCompetitionsApi } from "../../../services/competitions";
import CompetitionForm from "../CompetitionForm.vue";
import { csvName, isArchived, participantCsv, resultsUrlHint, type Coach, type Competition, type Row } from "../competitions";
import { competitionItself, WRITER_KEY } from "../writer";

const props = defineProps<{ competition: Competition; rows: readonly Row[]; coaches: readonly Coach[]; notInvitedCount: number }>();
const emit = defineEmits<{ email: []; loadGroup: []; removeNotInvited: [] }>();

const competitionsApi = createCompetitionsApi(inject(CLIENT_KEY)!);
const writer = inject(WRITER_KEY)!;
const router = useRouter();
const wide = useWideLayout();

// ---------------------------------------------------------------- The competition

const editing = ref(false);

async function save(body: Schemas["CompetitionCreate"]): Promise<void> {
  if (
    await writer.run(() => competitionsApi.update(props.competition.id, body), {
      competition: competitionItself,
      done: "✅ Compétition mise à jour.",
    })
  ) {
    editing.value = false;
  }
}

async function remove(): Promise<void> {
  if (
    !(await dialogs.confirm({
      title: "Supprimer la compétition",
      message: `Supprimer définitivement « ${props.competition.nom} » et sa liste de compétiteurs ?`,
      confirmLabel: "Supprimer",
      variant: "danger",
    }))
  ) {
    return;
  }
  const id = props.competition.id;
  if (await writer.run(() => competitionsApi.remove(id), { done: "🗑 Compétition supprimée." })) {
    editing.value = false;
    writer.dropped(id);
    await router.push({ query: {} });
  }
}

async function archive(archived: boolean): Promise<void> {
  const { id, nom } = props.competition;
  await writer.run(() => competitionsApi.setArchived(id, archived), {
    competition: competitionItself,
    done: archived ? `📦 « ${nom} » archivée.` : `♻️ « ${nom} » désarchivée.`,
  });
}

// ---------------------------------------------------------------- Exports

function exportCsv(): void {
  saveFile(csvBlob(participantCsv(props.rows)), csvName(props.competition));
}

/* Generated by the server, which needs the sign-in token: fetched through the API client, then saved. */
async function exportFile(kind: "excel" | "pdf"): Promise<void> {
  if (!writer.online()) {
    writer.toast("📴 Hors ligne : export impossible, utilisez l'export CSV.");
    return;
  }
  const id = props.competition.id;
  writer.toast("⏳ Génération du fichier en cours…", 60_000);
  try {
    const name =
      kind === "excel"
        ? await saveExport(competitionsApi.competitorsExcel(id), `competiteurs_${id}.xlsx`)
        : await saveExport(competitionsApi.competitorsPdf(id), `competiteurs_${id}.pdf`);
    writer.toast(`✅ Fichier « ${name} » téléchargé.`);
  } catch (e) {
    writer.toast(`❌ Échec de l'export : ${errorText(e)}`, 8000);
  }
}

// ---------------------------------------------------------------- MyCompet results

const fetching = ref(false);
const askUrl = ref(false);
const resultsUrl = ref("");

async function fetchResults(url = ""): Promise<void> {
  const { id, nom, url_resultats } = props.competition;
  fetching.value = true;
  askUrl.value = false;
  writer.toast(
    url || url_resultats ? `⏳ Recherche des résultats de « ${nom} »…` : `🔍 Recherche automatique des résultats MyCompet de « ${nom} »…`,
    6000,
  );
  try {
    await writer.run(() => competitionsApi.fetchResults(id, url), {
      done: (r) => `🏆 ${r.matched_count} résultat(s) associé(s) sur ${r.total_scraped} compétiteur(s) ALJ trouvé(s).`,
      refused: (e) => {
        if (e.code !== "needs_url") {
          return false;
        }
        resultsUrl.value = "";
        askUrl.value = true; // not found on MyCompet: the coach gives the page
        return true;
      },
    });
  } finally {
    fetching.value = false;
  }
}

const field = "rounded-lg border border-slate-300 bg-white px-2.5 py-1.5 text-[13px]";
</script>

<template>
  <div class="mt-2.5 flex flex-wrap gap-1.5 lg:mt-0 lg:max-w-[45%] lg:shrink-0 lg:justify-end" data-testid="detail-actions">
    <UiButton variant="muted" small data-testid="edit-comp" @click="editing = true">✏️ Modifier</UiButton>
    <UiButton v-if="wide" variant="muted" small data-testid="email-comp" @click="emit('email')">
      ✉️ Envoyer un email aux compétiteurs
    </UiButton>
    <UiMenu label="⋯ Plus" small :busy="fetching && 'Recherche MyCompet…'" aria-label="Plus d'actions" data-testid="detail-more">
      <UiMenuItem v-if="!wide" data-testid="email-comp" @select="emit('email')">✉️ Envoyer un email aux compétiteurs</UiMenuItem>
      <UiMenuItem data-testid="load-group" @select="emit('loadGroup')">🧗 Charger le groupe « Compétition »</UiMenuItem>
      <UiMenuItem data-testid="fetch-results" @select="fetchResults()">🏆 Trouver les résultats</UiMenuItem>
      <UiMenuItem data-testid="export-csv" :disabled="!rows.length" @select="exportCsv">📥 Export CSV</UiMenuItem>
      <UiMenuItem data-testid="export-excel-menu" :disabled="!rows.length" @select="exportFile('excel')">📊 Export Excel</UiMenuItem>
      <UiMenuItem data-testid="export-pdf-menu" :disabled="!rows.length" @select="exportFile('pdf')">📄 Export PDF</UiMenuItem>
      <UiMenuItem :data-testid="isArchived(competition) ? 'unarchive-comp' : 'archive-comp'" @select="archive(!isArchived(competition))">
        {{ isArchived(competition) ? "♻️ Désarchiver" : "📦 Archiver" }}
      </UiMenuItem>
      <UiMenuItem
        danger
        data-testid="remove-not-invited"
        :disabled="!notInvitedCount || writer.busy.value"
        title="Retirer de cette compétition tous les athlètes jamais invités (ils restent dans la base du club)"
        @select="emit('removeNotInvited')"
      >
        🗑️ Retirer les non invités ({{ notInvitedCount }})
      </UiMenuItem>
      <UiMenuItem danger data-testid="delete-comp" :disabled="writer.busy.value" @select="remove">🗑️ Supprimer</UiMenuItem>
    </UiMenu>

    <UiDialog v-model:open="editing" :title="`✏️ Modifier : ${competition.nom}`" wide data-testid="edit-dialog">
      <CompetitionForm
        v-if="editing"
        :competition="competition"
        :coaches="coaches"
        :busy="writer.busy.value"
        @save="save"
        @cancel="editing = false"
      />
    </UiDialog>
    <UiDialog v-model:open="askUrl" title="🏆 Résultats introuvables sur MyCompet" data-testid="results-dialog">
      <form class="flex flex-col gap-3" @submit.prevent="resultsUrl.trim() && fetchResults(resultsUrl.trim())">
        <p class="text-[13px]">
          Si les résultats de « {{ competition.nom }} » sont publiés, donnez l'adresse ou le numéro de leur page ({{ resultsUrlHint }}).
        </p>
        <input v-model="resultsUrl" data-testid="results-url" :class="field" :placeholder="resultsUrlHint" />
        <UiDialogActions>
          <UiButton variant="muted" @click="askUrl = false">Annuler</UiButton>
          <UiButton type="submit" data-testid="results-ok" :disabled="!resultsUrl.trim()">🔍 Chercher</UiButton>
        </UiDialogActions>
      </form>
    </UiDialog>
  </div>
</template>
