/* CSV files built in the browser (table exports). Every table export goes through toCsv(): member data comes from the
   public HelloAsso form, and a cell starting with = + - @ would run as a formula when the file is opened in a
   spreadsheet. Same rule as src/exports/spreadsheet_safety.py. Files generated by the server (FFME CSV) do not
   come here. */

export type Cell = string | number | boolean | null | undefined;

/** The cell, prefixed with ' when a spreadsheet would read it as a formula. Signed numbers and phone numbers are kept. */
export function csvSafe(value: string): string {
  if (!/^[=+\-@\t\r]/.test(value)) {
    return value;
  }
  if (/^[+-][\d\s().,]*$/.test(value)) {
    return value;
  }
  return `'${value}`;
}

function cell(value: Cell): string {
  const text = csvSafe(value == null ? "" : String(value));
  return `"${text.replace(/"/g, '""')}"`;
}

/** Rows separated by CRLF, cells by ; and quoted, with a BOM: Excel (French settings) opens it with the accents. */
export function toCsv(rows: readonly (readonly Cell[])[]): string {
  return "\uFEFF" + rows.map((row) => row.map(cell).join(";")).join("\r\n");
}

/** The CSV, as a file to save (lib/download.ts saveFile). */
export function csvBlob(rows: readonly (readonly Cell[])[]): Blob {
  return new Blob([toCsv(rows)], { type: "text/csv;charset=utf-8" });
}
